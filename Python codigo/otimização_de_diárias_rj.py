print(pd.DataFrame(res_reg).to_string(index=False, float_format=lambda x: f"{x:.3f}"))
print(f"Vetores de Suporte SVR: {len(regressores['SVR (Kernel RBF)'][0].named_steps['svr'].support_)} | Score OOB RF Clf: {classificadores['Random Forest Classifier (Otimizado)'][0].oob_score_:.3f}")

